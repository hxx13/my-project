-- 区域能力要能「关」，而且要能**全关**（架构设计 §7：区域是矩阵的**细分/收窄层**）。
--
-- 原设计靠「有没有行」区分：有行=配过、零行=从未配置→回落矩阵上限。
-- 这导致「配过且全关」与「从未配过」都是零行，组长**永远关不掉**（实测确认）。
--
-- 修法：保存时把**矩阵上限里的每一项都落一行**，用 enabled 表达开/关：
--   · 写了行就说明「这个区域被配过」→ 不再回落矩阵，按行的并集生效
--   · 全关 = 每个能力都是一行 enabled=0 → 并集为空 → 本区全部关闭
-- 读路径一律只看 enabled=1。
--
-- 幂等：重复执行会因列已存在而 benign 失败（故本文件只放这一条 DDL）。
ALTER TABLE cage_region_capability
    ADD COLUMN enabled TINYINT NOT NULL DEFAULT 1 COMMENT '1=开放；0=显式关闭（用于表达全关，同时标记本区域已配置）';
