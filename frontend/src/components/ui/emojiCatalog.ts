/** 全部 emoji（跨分类拍平，供全局搜索用） */
export const allEmojiItems: EmojiItem[] = emojiCatalog.flatMap((c) => c.items);

/**
 * 过滤：有 query 时跨全部分类按关键词/emoji 搜索；否则返回指定分类（默认第一个）。
 */
export function filterEmojis(query: string, categoryKey?: string): EmojiItem[] {
  const q = query.trim().toLowerCase();
  if (q) {
    return allEmojiItems.filter(
      (it) => it.emoji === q || it.keywords.toLowerCase().includes(q)
    );
  }
  const c = categoryKey ? emojiCatalog.find((x) => x.key === categoryKey) : emojiCatalog[0];
  return c?.items ?? [];
}
