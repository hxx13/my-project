/**
 * emojiCatalog — 共用 emoji 目录（业务无关）
 *
 * 供资产模块（AssetDetailDrawer / AdminAssetRecordPage / LocationTree）与
 * 物品台账（inventory）等模块的图标选择器复用。只导出数据与纯函数，
 * 不 import 任何业务 api，避免模块间耦合。
 *
 * 每项 = { emoji, keywords }；keywords 为中文搜索词（空格分隔），
 * 搜索时同时匹配 emoji 本身与关键词。
 */

export interface EmojiItem {
  emoji: string;
  /** 中文搜索关键词，空格分隔 */
  keywords: string;
}

export interface EmojiCategory {
  key: string;
  label: string;
  items: EmojiItem[];
}

type Row = [emoji: string, keywords: string];

function cat(key: string, label: string, rows: Row[]): EmojiCategory {
  return { key, label, items: rows.map(([emoji, keywords]) => ({ emoji, keywords })) };
}

